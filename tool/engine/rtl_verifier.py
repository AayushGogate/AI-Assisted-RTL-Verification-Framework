"""
RTL Verifier: Generates Directed Verilog Testbenches and Executes Real
Icarus Verilog Simulation Confirmation.
"""

import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Dict, Any, List, Optional, Tuple

def check_iverilog_installed() -> Tuple[bool, Optional[str]]:
    """
    Checks if iverilog and vvp are accessible on PATH.
    """
    iv = shutil.which("iverilog")
    vvp = shutil.which("vvp")
    if iv and vvp:
        return True, None
    missing = []
    if not iv:
        missing.append("iverilog")
    if not vvp:
        missing.append("vvp")
    guidance = (
        f"Missing simulator binary: {', '.join(missing)}. "
        "To enable real hardware simulation verification on Windows: "
        "Download and install Icarus Verilog (e.g. from https://bleyer.org/icarus/), "
        "and ensure C:\\iverilog\\bin (or your install path) is added to system PATH."
    )
    return False, guidance

def generate_directed_testbench(
    dut_plugin: Any,
    candidates: List[Dict[str, Any]]
) -> Tuple[str, List[Dict[str, Any]], List[Dict[str, Any]]]:
    """
    Builds a complete, synthesizable/simulatable Verilog testbench
    driving the REAL RTL module with the ML candidates.
    """
    module_name = getattr(dut_plugin, "RTL_MODULE", dut_plugin.DUT_NAME)
    widths = getattr(dut_plugin, "RTL_WIDTHS", {})
    drive_fn = dut_plugin.rtl_drive_fn

    sig_rows = []
    expected_rows = []

    for c in candidates:
        sig, exp = drive_fn(c["inputs"])
        sig_rows.append(sig)
        expected_rows.append(exp)

    in_names = list(sig_rows[0].keys())
    out_names = list(expected_rows[0].keys())

    tb_lines = [
        "`timescale 1ns/1ps",
        f"// Directed testbench generated by AI-Assisted RTL Verification Framework",
        f"// DUT: {dut_plugin.DUT_NAME} | Candidates: {len(candidates)}",
        f"module tb_{dut_plugin.DUT_NAME}_ml_verify;",
    ]

    # Port declarations
    for name in in_names:
        w = widths.get(name, 1)
        dim = f"[{w-1}:0] " if w > 1 else ""
        tb_lines.append(f"    reg  {dim}{name};")

    for name in out_names:
        w = widths.get(name, 1)
        dim = f"[{w-1}:0] " if w > 1 else ""
        tb_lines.append(f"    wire {dim}{name};")

    tb_lines.append("    integer pass_count = 0;")
    tb_lines.append("    integer fail_count = 0;")
    tb_lines.append("    integer i;")
    tb_lines.append("")

    # DUT Instantiation
    port_connections = [f".{n}({n})" for n in in_names + out_names]
    tb_lines.append(f"    {module_name} dut (")
    tb_lines.append("        " + ",\n        ".join(port_connections))
    tb_lines.append("    );")
    tb_lines.append("")

    # Stimulus block
    tb_lines.append("    initial begin")
    for idx, (sig, exp) in enumerate(zip(sig_rows, expected_rows)):
        tb_lines.append(f"        // Vector {idx + 1}")
        for n, val in sig.items():
            w = widths.get(n, 1)
            tb_lines.append(f"        {n} = {w}'d{val};")
        tb_lines.append("        #5;")

        checks = []
        for n, val in exp.items():
            w = widths.get(n, 1)
            checks.append(f"({n} === {w}'d{val})")

        check_cond = " && ".join(checks)
        tb_lines.append(f"        if ({check_cond}) begin")
        tb_lines.append("            pass_count = pass_count + 1;")
        tb_lines.append("        end else begin")
        tb_lines.append("            fail_count = fail_count + 1;")
        tb_lines.append(f'            $display("[FAIL] Candidate {idx + 1} mismatch at t=%0t", $time);')
        tb_lines.append("        end")
        tb_lines.append("")

    tb_lines.append(f'        $display("RTL_VERIFY_RESULT pass=%0d fail=%0d total=%0d", pass_count, fail_count, {len(sig_rows)});')
    tb_lines.append("        $finish;")
    tb_lines.append("    end")
    tb_lines.append("endmodule")

    tb_code = "\n".join(tb_lines)
    return tb_code, sig_rows, expected_rows

def verify_on_rtl(
    dut_plugin: Any,
    candidates: List[Dict[str, Any]],
    custom_rtl_path: Optional[str] = None
) -> Dict[str, Any]:
    """
    Executes directed simulation verification on the real RTL file.
    """
    if not candidates:
        return {
            "status": "skipped",
            "reason": "No candidates provided for verification.",
            "pass_count": 0,
            "fail_count": 0,
            "total": 0,
            "testbench_code": "",
            "simulator_output": "",
            "verified_closed_bins": [],
        }

    # Check iverilog availability
    has_iv, install_guidance = check_iverilog_installed()
    if not has_iv:
        # Still generate testbench for display so user can inspect it
        tb_code, _, _ = generate_directed_testbench(dut_plugin, candidates)
        return {
            "status": "skipped",
            "reason": "skipped: iverilog not found",
            "install_guidance": install_guidance,
            "pass_count": 0,
            "fail_count": 0,
            "total": len(candidates),
            "testbench_code": tb_code,
            "simulator_output": "Simulation skipped: Icarus Verilog (`iverilog` / `vvp`) is not present on PATH.",
            "verified_closed_bins": [],
        }

    # Locate RTL file
    if custom_rtl_path and Path(custom_rtl_path).exists():
        rtl_file = Path(custom_rtl_path).resolve()
    else:
        # Default bundled RTL
        default_rel = getattr(dut_plugin, "DEFAULT_RTL_PATH", f"bundled_rtl/{dut_plugin.DUT_NAME}.v")
        # Check relative to tool dir or root
        candidates_paths = [
            Path(__file__).resolve().parent.parent / default_rel,
            Path(__file__).resolve().parent.parent.parent / default_rel,
            Path(default_rel),
        ]
        rtl_file = None
        for p in candidates_paths:
            if p.exists():
                rtl_file = p.resolve()
                break

        if not rtl_file:
            tb_code, _, _ = generate_directed_testbench(dut_plugin, candidates)
            return {
                "status": "skipped",
                "reason": f"RTL file not found for DUT '{dut_plugin.DUT_NAME}'. Expected: {default_rel}",
                "install_guidance": "Please upload a Verilog (.v) file for this DUT.",
                "pass_count": 0,
                "fail_count": 0,
                "total": len(candidates),
                "testbench_code": tb_code,
                "simulator_output": f"Could not locate default RTL file: {default_rel}",
                "verified_closed_bins": [],
            }

    # Generate Testbench
    tb_code, _, _ = generate_directed_testbench(dut_plugin, candidates)

    # Use secure temporary directory with pathlib
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        tb_path = tmp_path / f"tb_{dut_plugin.DUT_NAME}_verify.v"
        sim_path = tmp_path / f"sim_{dut_plugin.DUT_NAME}.vvp"

        tb_path.write_text(tb_code, encoding="utf-8")

        # Compile with timeout 30s
        try:
            compile_res = subprocess.run(
                ["iverilog", "-o", str(sim_path), str(rtl_file), str(tb_path)],
                capture_output=True,
                text=True,
                timeout=30
            )
        except subprocess.TimeoutExpired:
            return {
                "status": "timeout",
                "reason": "Compilation timed out after 30 seconds.",
                "pass_count": 0,
                "fail_count": 0,
                "total": len(candidates),
                "testbench_code": tb_code,
                "simulator_output": "Compilation timed out after 30 seconds.",
                "verified_closed_bins": [],
            }
        except Exception as e:
            return {
                "status": "error",
                "reason": f"Subprocess invocation failed: {str(e)}",
                "pass_count": 0,
                "fail_count": 0,
                "total": len(candidates),
                "testbench_code": tb_code,
                "simulator_output": str(e),
                "verified_closed_bins": [],
            }

        if compile_res.returncode != 0:
            return {
                "status": "compile_error",
                "reason": "Icarus Verilog compilation failed.",
                "pass_count": 0,
                "fail_count": len(candidates),
                "total": len(candidates),
                "testbench_code": tb_code,
                "simulator_output": compile_res.stderr or compile_res.stdout,
                "verified_closed_bins": [],
            }

        # Run simulation with timeout 30s
        try:
            run_res = subprocess.run(
                ["vvp", str(sim_path)],
                capture_output=True,
                text=True,
                timeout=30
            )
        except subprocess.TimeoutExpired:
            return {
                "status": "timeout",
                "reason": "Simulation run timed out after 30 seconds.",
                "pass_count": 0,
                "fail_count": 0,
                "total": len(candidates),
                "testbench_code": tb_code,
                "simulator_output": "Simulation run timed out after 30 seconds.",
                "verified_closed_bins": [],
            }
        except Exception as e:
            return {
                "status": "error",
                "reason": f"Simulator invocation failed: {str(e)}",
                "pass_count": 0,
                "fail_count": 0,
                "total": len(candidates),
                "testbench_code": tb_code,
                "simulator_output": str(e),
                "verified_closed_bins": [],
            }

        sim_out = run_res.stdout
        pass_count = 0
        fail_count = 0
        total_tests = len(candidates)
        parsed = False

        for line in sim_out.splitlines():
            if "RTL_VERIFY_RESULT" in line:
                parsed = True
                parts = dict(p.split("=") for p in line.split()[1:] if "=" in p)
                pass_count = int(parts.get("pass", 0))
                fail_count = int(parts.get("fail", 0))
                total_tests = int(parts.get("total", len(candidates)))

        # Verified closed bins: candidates that passed RTL check and hit a missing bin
        verified_closed = []
        if pass_count > 0:
            for c in candidates:
                if c.get("closes_gap"):
                    verified_closed.append(c["actual_bin"])
            verified_closed = list(set(verified_closed))

        return {
            "status": "verified" if parsed and fail_count == 0 else ("failed" if fail_count > 0 else "unparsed"),
            "pass_count": pass_count,
            "fail_count": fail_count,
            "total": total_tests,
            "pass_rate": round(pass_count / total_tests * 100.0, 2) if total_tests > 0 else 0.0,
            "testbench_code": tb_code,
            "simulator_output": sim_out if sim_out.strip() else run_res.stderr,
            "verified_closed_bins": verified_closed,
            "rtl_source_file": str(rtl_file.name),
        }
